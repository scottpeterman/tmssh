const ColorScheme *find_scheme(const char *name) {
    if (name == nullptr) {
        return nullptr;
    }
    for (const ColorScheme &scheme : kSchemes) {
        if (std::strcmp(scheme.name, name) == 0) {
            return &scheme;
        }
    }
    return nullptr;
}

const ColorScheme *schemes(std::size_t &count) {
    count = sizeof kSchemes / sizeof kSchemes[0];
    return kSchemes;
}

